package ru.yandex.practicum.enums;

/**
 * Перечисление возможных статусов доставки.
 * Определяет все состояния, в которых может находиться доставка.
 */
public enum DeliveryState {

    /**
     * Доставка создана, но еще не начата.
     */
    CREATED,

    /**
     * Доставка находится в процессе выполнения.
     */
    IN_PROGRESS,

    /**
     * Доставка успешно завершена.
     */
    DELIVERED,

    /**
     * Доставка не удалась.
     */
    FAILED,

    /**
     * Доставка отменена.
     */
    CANCELLED
}